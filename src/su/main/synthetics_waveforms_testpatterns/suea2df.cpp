static void calc_area(float vmax, float dtx, float dtz, 
		int *limits, int i, int j, int k, int nxpadded, int nzpadded)
{
	 limits[0] = i - NINT(vmax*k*dtx) - 10;
	 limits[1] = i + NINT(vmax*k*dtx) + 10;
	 limits[2] = j - NINT(vmax*k*dtz) - 10;
	 limits[3] = j + NINT(vmax*k*dtz) + 10;

	 if (limits[0] < 2) limits[0] = 2;

	 if (limits[1] > nxpadded-3) limits[1] = nxpadded-3;

	 if (limits[2] < 2) limits[2] = 2;

	 if (limits[3] > nzpadded-3) limits[3] = nzpadded-3;	 
}




/* Library version of SUEA2DF
 *
 * The main program (the parameters, the files of the model, of the snapshots and of the seismograms, the character headers) is left
 * to the caller. The computation is made in steps, on a model that the caller makes, steps and frees, and all of the arrays that the
 * caller gives are not changed:
 *
 *	su_ea2df_create:	pads and checks the model, makes the source, the boundary tapers and the traveltimes of a plane wave
 *	su_ea2df_step:		the next time step (the program's loop body), recording the horizontal and vertical lines
 *	su_ea2df_snapshot:	copies a field of the model (without the boundary layers) at this time
 *	su_ea2df_info, su_ea2df_lines:	the sizes, and the recorded lines (after the model has been stepped nt times)
 *	su_ea2df_free:		frees the model
 *
 * The 2-D arrays that are given are [nz][nx] (x the fast axis), as the program reads them: the stiffnesses c11 and c55, and (with
 * aniso) c13, c33, c15 and c35, the density (rho) and (with qsw) the Q-factor.
 *
 * Differences from the program:
 *  - The padding of the model (pad_float_2D) is done correctly: the model is copied into the padded array, shifted by the widths of
 *    the boundary layers, and the edges are extended into the layers. The program's copy loops stopped at the end of the unpadded
 *    model (so that the last rows and columns of the model were lost, and the model was shifted in the padded array), with the
 *    layers beyond it filled from the last row and column.
 *  - The loop does nt = NINT((lt-ft)/dt)+1 steps. The program counted the time in single precision (t=t+dt while t<=lt), which could
 *    be one step more or less than the nt of the arrays that record it.
 *  - The checks of the parameters return a code.
 */

struct Ea2dfModel {
	int nx, nz, nxpadded, nzpadded, nt, k, ns, aniso, qsw, tsw, stype, bc[4], wbc[4], is, js, hs1, vs2, limits[4];
	float dt, dx, dz, fx, fz, sang, vlim[2], dtx, dtz;
	float **c11, **c55, **c13, **c33, **c15, **c35, **rho, **q;
	float **u, **w, **txx, **tzz, **txz;
	float *source, *bc0, *bc1, *bc2, *bc3, *vl, *vr, *vb, *ttl, *ttr, *ttb;
	float **hu, **hw, **vu, **vw;	/* the lines recorded: [nt][nxpadded], [nt][nzpadded] */
};

/* the padding of an [n2][n1] array to [n2+padval[0]+padval[2]][n1+padval[1]+padval[3]]: copied, with the edges extended */
static void pad_model(int n1, int n2, int *padval, const float *in, float **out)
{
	int ix1, ix2, j1, j2, n1padded = n1+padval[1]+padval[3], n2padded = n2+padval[0]+padval[2];
	for (ix2=0; ix2<n2padded; ++ix2) {
		j2 = ix2-padval[0];
		if (j2<0) j2 = 0;
		if (j2>n2-1) j2 = n2-1;
		for (ix1=0; ix1<n1padded; ++ix1) {
			j1 = ix1-padval[1];
			if (j1<0) j1 = 0;
			if (j1>n1-1) j1 = n1-1;
			out[ix2][ix1] = in[(size_t)j2*n1+j1];
		}
	}
}

static void ea_minmax(float **a, int nxpadded, int nzpadded, float *amin, float *amax)
{
	int ix, iz;
	*amin = *amax = a[0][0];
	for (iz=0; iz<nzpadded; ++iz)
		for (ix=0; ix<nxpadded; ++ix) {
			if (a[iz][ix]<*amin) *amin = a[iz][ix];
			if (a[iz][ix]>*amax) *amax = a[iz][ix];
		}
}

/* Returns the model, or NULL and in *err: -1 or -2 the source is outside of the model in x or z, -3 parameters that are not allowed,
 * -4 an unknown source or wave type, -5 a recording line outside of the model, -6 a density or Q that is not positive. */
struct Ea2dfModel *su_ea2df_create(float dt, float ft, float lt, int nx, float dx, float fx, int nz, float dz, float fz,
	float sx, float sz, const char *stype, float sang, const char *wtype, float ts, float favg,
	int qsw, int aniso, int tsw, const int *bcin, float bc_a, float bc_r, float hsz, float vsx,
	const float *c11in, const float *c55in, const float *rhoin, const float *c13in, const float *c33in,
	const float *c15in, const float *c35in, const float *qin, int *err)
{
	struct Ea2dfModel *M;
	int i, j, ix, iz, nxpadded, nzpadded, nt, ns, ngrids = 0;
	int bc[4], wbc[4];
	float xmax, zmax, rhomin, rhomax, c11min, c11max, c55min, c55max, dummy, sa, ca, p;
	float **c11, **c55, **rho, **c13 = NULL, **c33 = NULL, **c15 = NULL, **c35 = NULL, **q = NULL;
	float *bc0, *bc1, *bc2, *bc3, *source, *vl, *vr, *vb, *ttl, *ttr, *ttb;
	float vlim[2];
	int stype_code;

	*err = 0;
	if (dt<=0.0 || dx<=0.0 || dz<=0.0 || nx<5 || nz<5 || lt<ft || ts<0.0 || favg<=0.0) { *err = -3; return NULL; }
	if (strcmp(stype,"p")==0) stype_code = 0;
	else if (strcmp(stype,"v")==0) stype_code = 1;
	else if (strcmp(stype,"pw")==0) stype_code = 2;
	else { *err = -4; return NULL; }
	if (strcmp(wtype,"ri")!=0 && strcmp(wtype,"dg")!=0 && strcmp(wtype,"ga")!=0 && strcmp(wtype,"sp")!=0 && strcmp(wtype,"sp2")!=0) {
		*err = -4; return NULL;
	}
	for (i=0; i<4; i++) { bc[i] = bcin[i]; if (bc[i]<0) { *err = -3; return NULL; } }

	/* calculate maximum model coordinates */
	xmax = fx + dx*nx;
	zmax = fz + dz*nz;

	/* check to see if source is inside the model */
	if ((sx<fx) || (sx>xmax)) { *err = -1; return NULL; }
	if ((sz<fz) || (sz>zmax)) { *err = -2; return NULL; }

	for (i=0; i<4; i++) {
		wbc[i] = 2;
		if (bc[i]>2) wbc[i] = bc[i];
	}
	bc0 = ealloc1float(bc[0]+1);
	bc1 = ealloc1float(bc[1]+1);
	bc2 = ealloc1float(bc[2]+1);
	bc3 = ealloc1float(bc[3]+1);
	bc0[0] = bc_a;
	bc1[0] = bc_a;
	bc2[0] = bc_a;
	bc3[0] = bc_a;
	for (j=1; j<bc[0]; j++) bc0[j] = bc0[j-1]*bc_a*pow(j,-bc_r);
	for (j=1; j<bc[1]; j++) bc1[j] = bc1[j-1]*bc_a*pow(j,-bc_r);
	for (j=1; j<bc[2]; j++) bc2[j] = bc2[j-1]*bc_a*pow(j,-bc_r);
	for (j=1; j<bc[3]; j++) bc3[j] = bc3[j-1]*bc_a*pow(j,-bc_r);

	/* the recording lines */
	M = (struct Ea2dfModel*)calloc(1,sizeof(struct Ea2dfModel));
	M->hs1 = NINT( (hsz - fz)/dz )+wbc[0];		/*horizontal line*/
	M->vs2 = NINT((vsx - fx)/dx )+wbc[1];		/*vertical line*/

	/* pad the nx and nz dimensions for boundary condition layers */
	nxpadded = nx+wbc[1]+wbc[3];
	nzpadded = nz+wbc[0]+wbc[2];
	if (M->hs1<0 || M->hs1>=nzpadded || M->vs2<0 || M->vs2>=nxpadded) {
		*err = -5; free(M); free1float(bc0); free1float(bc1); free1float(bc2); free1float(bc3); return NULL;
	}
	nt = NINT((lt-ft)/dt)+1;

	M->dtx = dt/dx; M->dtz = dt/dz;
	M->is = NINT((-fx+sx)/dx)+wbc[1]; M->js = NINT((-fz+sz)/dz)+wbc[0];

	/* the model, padded */
	c11 = ealloc2float(nxpadded,nzpadded);
	c55 = ealloc2float(nxpadded,nzpadded);
	rho = ealloc2float(nxpadded,nzpadded);
	pad_model(nx,nz,wbc,c11in,c11);
	pad_model(nx,nz,wbc,c55in,c55);
	pad_model(nx,nz,wbc,rhoin,rho);
	ngrids = 3;
	if (aniso==1) {
		c33 = ealloc2float(nxpadded,nzpadded);
		c13 = ealloc2float(nxpadded,nzpadded);
		c15 = ealloc2float(nxpadded,nzpadded);
		c35 = ealloc2float(nxpadded,nzpadded);
		pad_model(nx,nz,wbc,c33in,c33);
		pad_model(nx,nz,wbc,c13in,c13);
		pad_model(nx,nz,wbc,c15in,c15);
		pad_model(nx,nz,wbc,c35in,c35);
	}
	if (qsw==1) {
		q = ealloc2float(nxpadded,nzpadded);
		pad_model(nx,nz,wbc,qin,q);
	}

	/* we need to invert density */
	ea_minmax(rho,nxpadded,nzpadded,&rhomin,&rhomax);
	if (rhomin<=0.0) {
		*err = -6;
		free2float(c11); free2float(c55); free2float(rho);
		if (aniso==1) { free2float(c33); free2float(c13); free2float(c15); free2float(c35); }
		if (qsw==1) free2float(q);
		free(M); free1float(bc0); free1float(bc1); free1float(bc2); free1float(bc3);
		return NULL;
	}
	rhomin = rhomax = 1/rho[0][0];
	for (iz=0; iz<nzpadded; ++iz) {
		for (ix=0; ix<nxpadded; ++ix) {
			/* rho = 1/rho */
			rho[iz][ix] = 1/rho[iz][ix];
			rhomin = MIN(rhomin,rho[iz][ix]);
			rhomax = MAX(rhomax,rho[iz][ix]);
		}
	}
	ea_minmax(c11,nxpadded,nzpadded,&c11min,&c11max);
	ea_minmax(c55,nxpadded,nzpadded,&c55min,&c55max);
	(void)c55min; (void)c55max; (void)dummy; (void)ngrids;

	vlim[0] = sqrt(c11min*rhomax);
	vlim[1] = sqrt(c11max*rhomin);

	if (qsw==1) {
		ea_minmax(q,nxpadded,nzpadded,&dummy,&dummy);
		/* scale Q-factor */
		for (i=0; i<nxpadded; i++){
			for (j=0; j<nzpadded; j++) {
				q[j][i] = exp(-PI*dt*favg/q[j][i]);
			}
		}
	}

	/* set arrays for plane boundary conditions */
	ttl = ealloc1float(nzpadded);
	ttb = ealloc1float(nxpadded);
	ttr = ealloc1float(nzpadded);
	vl = ealloc1float(nzpadded);
	vb = ealloc1float(nxpadded);
	vr = ealloc1float(nzpadded);

	/* note that rho = 1/density now */
	for (j=0; j<nzpadded; ++j) {
		vl[j]=sqrt(c11[j][wbc[1]]*rho[j][wbc[1]]);
		vr[j]=sqrt(c11[j][nxpadded-wbc[3]-1]*rho[j][nxpadded-wbc[3]-1]);
	}
	for (i=0; i<nxpadded; ++i) {
		vb[i]=sqrt(c11[nzpadded-wbc[2]-1][i]*rho[nzpadded-wbc[2]-1][i]);
	}
	for (i=0; i<nxpadded; ++i) ttb[i] = 0.0;

	/* ttb: traveltime from source to location on bottom */
	sa=sin(PI*sang/180.);ca=cos(PI*sang/180.);

	if(sang>=0&&sang<90){
		ttb[0]=(-wbc[1])*sa*dx/vb[wbc[1]];
		for (i=1; i<nxpadded; ++i) {
			ttb[i]=ttb[i-1]+dx*sa/vb[i];
		}
	}

	if(sang>-90&&sang<0){
		ttb[nxpadded-1]=-(-wbc[3])*sa*dx/vl[nxpadded-wbc[3]-1];
		for (i=nxpadded-1; i>0; --i) {
			ttb[i-1]=ttb[i]-dx*sa/vb[i];
		}
	}

	/* ttl, ttr: traveltimes from source to location on LHS, RHS */
	sa=sin(PI*sang/180.);
	ca=cos(PI*sang/180.);
	p=sin(sang*PI/180.)/vl[nzpadded-wbc[2]-1];

	ttl[nzpadded-1]=(-wbc[2])*ca*dz/vl[nzpadded-wbc[2]-1];
	for (j=nzpadded-1; j>0; --j) {
		sa=sin(asin(p*vl[j]));
		ca=cos(asin(p*vl[j]));
		ttl[j-1]=ttl[j]+dz*ca/vl[j];
	}

	sa=sin(PI*sang/180.);
	ca=cos(PI*sang/180.);
	p=sin(sang*PI/180.)/vr[nzpadded-wbc[2]-1];
	ttr[nzpadded-1]=(-wbc[2])*ca*dz/vr[nzpadded-wbc[2]-1];

	for (j=nzpadded-1; j>0; --j) {
		sa=sin(asin(p*vr[j]));
		ca=cos(asin(p*vr[j]));
		ttr[j-1]=ttr[j]+dz*ca/vr[j];
	}

	/* get source function */
	ns = NINT(ts/dt)+1;
	source = ealloc1float(ns);
	get_source(dt,ts,favg,(char*)wtype,source);

	/* allocate space for variables */
	M->u = ealloc2float(nxpadded,nzpadded);
	M->w = ealloc2float(nxpadded+1,nzpadded);
	M->txx = ealloc2float(nxpadded+1,nzpadded);
	M->tzz = ealloc2float(nxpadded+1,nzpadded);
	M->txz = ealloc2float(nxpadded,nzpadded);
	memset(M->u[0],0,sizeof(float)*(size_t)nxpadded*nzpadded);
	memset(M->w[0],0,sizeof(float)*(size_t)(nxpadded+1)*nzpadded);
	memset(M->txx[0],0,sizeof(float)*(size_t)(nxpadded+1)*nzpadded);
	memset(M->tzz[0],0,sizeof(float)*(size_t)(nxpadded+1)*nzpadded);
	memset(M->txz[0],0,sizeof(float)*(size_t)nxpadded*nzpadded);

	M->hu = ealloc2float(nxpadded,nt);
	M->hw = ealloc2float(nxpadded,nt);
	M->vu = ealloc2float(nzpadded,nt);
	M->vw = ealloc2float(nzpadded,nt);

	M->nx = nx; M->nz = nz; M->nxpadded = nxpadded; M->nzpadded = nzpadded; M->nt = nt; M->k = 0; M->ns = ns;
	M->aniso = aniso; M->qsw = qsw; M->tsw = tsw; M->stype = stype_code;
	for (i=0; i<4; i++) { M->bc[i] = bc[i]; M->wbc[i] = wbc[i]; }
	M->dt = dt; M->dx = dx; M->dz = dz; M->fx = fx; M->fz = fz; M->sang = sang;
	M->vlim[0] = vlim[0]; M->vlim[1] = vlim[1];
	M->c11 = c11; M->c55 = c55; M->c13 = c13; M->c33 = c33; M->c15 = c15; M->c35 = c35; M->rho = rho; M->q = q;
	M->source = source; M->bc0 = bc0; M->bc1 = bc1; M->bc2 = bc2; M->bc3 = bc3;
	M->vl = vl; M->vr = vr; M->vb = vb; M->ttl = ttl; M->ttr = ttr; M->ttb = ttb;
	return M;
}

/* The sizes: the padded model, the number of time steps, the widths of the boundary layers wbc[4], and the number of steps done */
void su_ea2df_info(const struct Ea2dfModel *M, int *nxpadded, int *nzpadded, int *nt, int *wbc, int *done)
{
	int i;
	*nxpadded = M->nxpadded; *nzpadded = M->nzpadded; *nt = M->nt; *done = M->k;
	for (i=0; i<4; i++) wbc[i] = M->wbc[i];
}

/* The lines recorded, each [nt][n]: hu, hw (the horizontal line, n=nxpadded), vu, vw (the vertical line, n=nzpadded) */
void su_ea2df_lines(const struct Ea2dfModel *M, const float **hu, const float **hw, const float **vu, const float **vw)
{
	*hu = M->hu[0]; *hw = M->hw[0]; *vu = M->vu[0]; *vw = M->vw[0];
}

/* Copies a field without the boundary layers, [nz][nx], to out: which is 0 u, 1 w, 2 txx, 3 tzz, 4 txz */
void su_ea2df_snapshot(const struct Ea2dfModel *M, int which, float *out)
{
	float **f = (which==0) ? M->u : (which==1) ? M->w : (which==2) ? M->txx : (which==3) ? M->tzz : M->txz;
	int i, j;
	for (j=0; j<M->nz; ++j)
		for (i=0; i<M->nx; ++i)
			out[(size_t)j*M->nx+i] = f[j+M->wbc[0]][i+M->wbc[1]];
}

/* The next time step. Returns 1 if the model was stepped, 0 if it has done nt steps. */
int su_ea2df_step(struct Ea2dfModel *M)
{
	int ifx, ilx, jfz, jlz, i, j, k = M->k;
	int nxpadded = M->nxpadded, nzpadded = M->nzpadded, ns = M->ns;
	int *wbc = M->wbc, *bc = M->bc, *limits = M->limits;
	float **u = M->u, **w = M->w, **txx = M->txx, **tzz = M->tzz, **txz = M->txz;
	float **c11 = M->c11, **c55 = M->c55, **c33 = M->c33, **c13 = M->c13, **c15 = M->c15, **c35 = M->c35, **rho = M->rho, **q = M->q;
	float dtx = M->dtx, dtz = M->dtz, dt = M->dt, dx = M->dx, dz = M->dz, sang = M->sang;
	float *source = M->source;
	int is = M->is, js = M->js, aniso = M->aniso, qsw = M->qsw, tsw = M->tsw, stype = M->stype;

	if (k>=M->nt) return 0;

	/* calculate area for active grid */
	calc_area(M->vlim[1],dtx,dtz,limits,is,js,k,nxpadded,nzpadded);

	ifx=limits[0];
	ilx=limits[1];
	jfz=limits[2];
	jlz=limits[3];

	if (stype==2){
		ifx=2;
		ilx=nxpadded-3;
		jfz=2;
		jlz=nzpadded-3;
	}

	/* introduce velocity source */
	if (k<ns) {
		if (stype==1)
			add_v_source(u,w,dt*source[k],is,js);
	}

	/* update velocities */
	if(tsw==0)
		update_vel(ifx,ilx,jfz,jlz,u,w,txx,tzz,txz,
				rho,c55,dtx,dtz);
	if(tsw==1)
		update_vel_tsw(ifx,ilx,jfz,jlz,u,w,txx,tzz,
				txz,rho,c55,dtx,dtz);

	/* introduce plane wave velocity source */
	if (stype==2){
		add_pw_source_V(u,w,txx,tzz,txz,c11,c55,
				source,sang,wbc[1],
				nxpadded-wbc[3]-1,
				wbc[0],nzpadded-wbc[2]-1,
				ns,k,dx,dz,dt,M->vl,M->vb,M->vr,
				M->ttl,M->ttb,M->ttr);
	}

	/* apply free surface bc for velocities */
	if(bc[0]==2) fs4v_bc_top(u,w,c11,c55,nxpadded,nzpadded);

	/* apply symmetry bc for velocities */
	if(bc[0]==1) sym4v_bc_top(u,w,nxpadded,nzpadded);
	if(bc[1]==1) sym4v_bc_left(u,w,nxpadded,nzpadded);
	if(bc[2]==1) sym4v_bc_bot(u,w,nxpadded,nzpadded);
	if(bc[3]==1) sym4v_bc_right(u,w,nxpadded,nzpadded);

	/* introduce stress source */
	if (k<ns) {
		if (stype==0)
			add_p_source(txx,tzz,dt*source[k],is,js);
	}

	/* update stresses */
	if(!aniso) {  /* isotropic */
		update_stress_iso(ifx,ilx,jfz,jlz,u,w,txx,tzz,txz,
				c11,c55,dtx,dtz);
	} else {
		update_stress_ani(ifx,ilx,jfz,jlz,u,w,txx,tzz,txz,
				c11,c55,c33,c13,c15,c35,
				dtx,dtz);
	}

	/* introduce plane wave stress source */
	if (stype==2) {
		add_pw_source_S(u,w,txx,tzz,txz,c11,c55,
				source,sang,wbc[1],
				nxpadded-wbc[3]-1,wbc[0],
				nzpadded-wbc[2]-1,ns,k,
				dx,dz,dt,M->vl,M->vb,M->vr,M->ttl,
				M->ttb,M->ttr);
	}

	/* apply free surface bc for stresses */
	if(bc[0]==2) fs4s_bc_top(txx,tzz,txz,nxpadded,nzpadded);

	/* apply symmetry bc for stresses */
	if(bc[0]==1) sym4s_bc_top(txx,tzz,txz,nxpadded,nzpadded);
	if(bc[1]==1) sym4s_bc_left(txx,tzz,txz,nxpadded,nzpadded);
	if(bc[2]==1) sym4s_bc_bot(txx,tzz,txz,nxpadded,nzpadded);
	if(bc[3]==1) sym4s_bc_right(txx,tzz,txz,nxpadded,nzpadded);

	/* apply absorbing bc */
	if(bc[0]>2)
		abs_bc_top(u,w,txx,tzz,txz,nxpadded,nzpadded,
				M->bc0,bc,wbc,ifx,ilx);
	if(bc[1]>2)
		abs_bc_left(u,w,txx,tzz,txz,nxpadded,nzpadded,
				M->bc1,bc,wbc,jfz,jlz);
	if(bc[2]>2)
		abs_bc_bot(u,w,txx,tzz,txz,nxpadded,nzpadded,
				M->bc2,bc,wbc,ifx,ilx);
	if(bc[3]>2)
		abs_bc_right(u,w,txx,tzz,txz,nxpadded,nzpadded,
				M->bc3,bc,wbc,jfz,jlz);

	/* attenuation */
	if(qsw==1) {
		for (j=jfz-2; j<jlz+2; j++){
			for (i=ifx-2; i<ilx+2; i++) {
				u[j][i]*=q[j][i];
				w[j][i]*=q[j][i];
				txx[j][i]*=q[j][i];
				tzz[j][i]*=q[j][i];
				txz[j][i]*=q[j][i];
			}
		}
	}

	/* store wave motion (seismograms) */
	for (i=0 ; i < nxpadded ; ++i) {
		M->hu[k][i] = u[M->hs1][i];
		M->hw[k][i] = w[M->hs1][i];
	}
	for (j=0 ; j < nzpadded ; ++j) {
		M->vu[k][j] = u[j][M->vs2];
		M->vw[k][j] = w[j][M->vs2];
	}

	M->k = k+1;
	return 1;
}

void su_ea2df_free(struct Ea2dfModel *M)
{
	if (M==NULL) return;
	free2float(M->c11); free2float(M->c55); free2float(M->rho);
	if (M->aniso==1) { free2float(M->c33); free2float(M->c13); free2float(M->c15); free2float(M->c35); }
	if (M->qsw==1) free2float(M->q);
	free2float(M->u); free2float(M->w); free2float(M->txx); free2float(M->tzz); free2float(M->txz);
	free2float(M->hu); free2float(M->hw); free2float(M->vu); free2float(M->vw);
	free1float(M->source); free1float(M->bc0); free1float(M->bc1); free1float(M->bc2); free1float(M->bc3);
	free1float(M->vl); free1float(M->vr); free1float(M->vb); free1float(M->ttl); free1float(M->ttr); free1float(M->ttb);
	free(M);
}
