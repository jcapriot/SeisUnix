/* Low-pass filter, integration and phase shift for input data (the filtering of the program, with the tables of the
 * frequency domain made at each call instead of the first one only).
 *   trace[nt]	the trace, replaced by the filtered and phase-shifted one
 *   fmax	high cut frequency
 *   ls		1 for a line source, 0 for a point source
 *   trf[nt+2*m]	the filtered, integrated and phase-shifted trace, with m samples of the end before and after
 * Returns 1 if the padded length is too long. */
static int filt(float *trace,int nt,float dt,float fmax,int ls,int m,float *trf)
{
	int  it, iw, itemp, itaper, nw, nwf, nfft;
	float temp, ftaper, const2, dw;

	fmax *= 2.0*PI;
	ftaper = 0.1*fmax;
	const2 = 0.5*sqrt(2.0);

	nfft = npfaro(nt+2*m, 2*(nt+2*m));
	if (nfft >= SU_NFLTS || nfft >= 720720) return 1;
	nw = nfft/2 + 1;
	dw = 2.0*PI/(nfft*dt);

	itaper = 0.5+ftaper/dw;
	std::vector<float> taper(2*itaper+1);
	for (iw=-itaper; iw<=itaper; ++iw) {
		temp = (float)iw/(1.0+itaper);
		taper[iw+itaper] = (1-temp)*(1-temp)*(temp+2)/4;
	}

	nwf = 0.5+fmax/dw;
	if (nwf>nw-itaper-1) nwf = nw-itaper-1;
	if (nwf<0) nwf = 0;
	std::vector<float> amp(nwf+itaper+1), ampi(nwf+itaper+1);
	amp[0] = ampi[0] = 0.;
	for (iw=1; iw<=nwf+itaper; ++iw) {
		amp[iw] = sqrt(dw*iw)/nfft;
		ampi[iw] = 0.5/(1-cos(iw*dw*dt));
	}

	std::vector<float> rt(nfft);
	std::vector<std::complex<float> > ct(nw);

	memcpy(rt.data(), trace, nt*FSIZE);
	memset((void *) (rt.data() + nt), 0, (nfft-nt)*FSIZE);
	pfarc(1, nfft, rt.data(), ct.data());

	for (iw=nwf-itaper; iw<=nwf+itaper; ++iw) {
		if (iw<0 || iw>=nw) continue;
		itemp = iw-(nwf-itaper);
		ct[iw] = taper[itemp]*ct[iw];
	}
	for (iw=nwf+itaper+1; iw<nw; ++iw) ct[iw] = 0.;

	for (iw=0; iw<=nwf+itaper && iw<nw; ++iw) {
		float r = ct[iw].real(), i = ct[iw].imag();
		if (!ls) {
			/* phase shifts PI/4 + PI/4 (Half derivative) */
			ct[iw] = std::complex<float>(-i*amp[iw], r*amp[iw]);
		} else {
			/* phase shifts PI/4 -Half derivative */
			ct[iw] = std::complex<float>((r-i)*amp[iw]*const2, (r+i)*amp[iw]*const2);
		}
	}

	pfacr(-1, nfft, ct.data(), rt.data());

	/* Load traces back in */
	for (it=0; it<nt; ++it) trace[it] = rt[it];

	/* Integrate traces */
	for (iw=0; iw<=nwf+itaper && iw<nw; ++iw) ct[iw] *= ampi[iw];
	pfacr(-1, nfft, ct.data(), rt.data());
	for (it=0; it<m; ++it) trf[it] = rt[nfft-m+it];
	for (it=0; it<nt+m; ++it) trf[it+m] = rt[it];
	return 0;
}

/* the rows of a flat array */
static void rows_of(const float *base, int nrow, int len, std::vector<float*> &rows)
{
	int i;
	rows.resize(nrow);
	for (i=0; i<nrow; i++) rows[i] = (float *) (base + (size_t) i*len);
}
static int mig2d(float *trace,int nt,float ft,float dt,
	float sx,float gx,float **mig,float aperx,
  	int nx,float fx,float dx,float nz,float fz,float dz,
	int ls,int mtmax,float dxm,float fmax,float angmax,
        float **tbs,float **tbg,float **pbs,
        float **pbg,float **angbs,float **angbg,int nr,float **tsum,
        int nzt,float fzt,float dzt,int nxt,float fxt,float dxt,float *szif,
        float nangls,float nanglg,float **sigbs,float **sigbg)
/*****************************************************************************
Migrate one trace 
******************************************************************************
Input:
*trace		one seismic trace 
nt		number of time samples in seismic trace
ft		first time sample of seismic trace
dt		time sampleing interval in seismic trace
sx,gx		lateral coordinates of source and geophone 
aperx		lateral aperature in migration
nx,fx,dx,nz,fz,dz  dimension parameters of migration region
ls		=1 for line source; =0 for point source
mtmax		number of time samples in triangle filter
dxm		midpoint sampling interval
fmax		frequency-highcut for input trace	 
angmax		migration angle aperature from vertical 	 
(tb,pb,sigb,angb)s,g	reference traveltime, lateral slowness, cosine of 
		incident angle, and emergent angle
nr		number of lateral samples in reference quantities
tsum		sum of residual traveltimes from shot and receiver
nxt,fxt,dxt,nzt,fzt,dzt		dimension parameters of traveltime table
szif            array[] of the z component of the recording surface (ignored)
nangls,nanglg   Angles that the normal unit vector of the current surface
                forms with the vertical at source and geophone locations.
Output:
mig		migrated section
*****************************************************************************/
{
	int nxf,nxe,nxtf,nxte,ix,iz,iz0,izt0,nzp,jrs,jrg,jz,jt,mt,jx;
	float xm,x,dis,rxz,ar,srs,srg,srs0,srg0,sigp,z0,rdz,ampd,res0,
	      angs,angg,ax,ax0,pmin,odt=1.0/dt,pd,az,sz,sz0,sigmas,sigmag,
	      at,td,res,temp,sigs,sigg;
	float **tmt,**ampt,**ampti,*tm,*amp,*ampi,*tzt,*trf,*zpt;
	int status = 0;

	tmt = alloc2float(nzt,nxt);
	ampt = alloc2float(nzt,nxt);
	ampti = alloc2float(nzt,nxt);
	tm = alloc1float(nzt);
	tzt = alloc1float(nzt);
	amp = alloc1float(nzt);
	ampi = alloc1float(nzt);
	zpt = alloc1float(nxt);
	trf = alloc1float(nt+2*mtmax);
	memset((void *) tmt[0],0,nxt*nzt*sizeof(float));
	memset((void *) ampt[0],0,nxt*nzt*sizeof(float));
	memset((void *) ampti[0],0,nxt*nzt*sizeof(float));
	memset((void *) tm,0,nzt*sizeof(float));
	memset((void *) tzt,0,nzt*sizeof(float));
	memset((void *) amp,0,nzt*sizeof(float));
	memset((void *) ampi,0,nzt*sizeof(float));
	memset((void *) zpt,0,nxt*sizeof(float));

	z0 = (fz-fzt)/dzt;
	rdz = dz/dzt;
	pmin = 1.0/(2.0*dxm*fmax);
	
	if (filt(trace,nt,dt,fmax,ls,mtmax,trf)) { status = 6; goto done; }

	xm = 0.5*(sx+gx);
	rxz = (angmax==90)?0.0:1.0/tan(angmax*PI/180.);
	nxtf = (xm-aperx-fxt)/dxt;
	if(nxtf<0) nxtf = 0;
	nxte = (xm+aperx-fxt)/dxt+1;
	if(nxte>=nxt) nxte = nxt-1;

	/* compute amplitudes and filter length	*/
	for(ix=nxtf; ix<=nxte; ++ix){
		x = fxt+ix*dxt;
		dis = (xm>=x)?xm-x:x-xm;
		izt0 = ((dis-dxt)*rxz-fzt)/dzt-1;
		if(izt0<0) izt0 = 0;
		if(izt0>=nzt) izt0 = nzt-1;

		ar = (sx>=x)?(sx-x)/dx:(x-sx)/dx;
		jrs = (int)ar;
		if(jrs>nr-2) jrs = nr-2;
		srs = ar-jrs;
		srs0 = 1.0-srs;
		ar = (gx>=x)?(gx-x)/dx:(x-gx)/dx;
		jrg = (int)ar;
		if(jrg>nr-2) jrg = nr-2;
		srg = ar-jrg;
		srg0 = 1.0-srg;
		sigp = ((sx-x)*(gx-x)>0)?1.0:-1.0;
                sigs = ((sx-x)<0)?1.0:-1.0;
                sigg = ((gx-x)<0)?1.0:-1.0;
		zpt[ix] = fzt+(nzt-1)*dzt;

		for(iz=izt0; iz<nzt; ++iz){
			angs = srs0*angbs[jrs][iz]+srs*angbs[jrs+1][iz];
                        angs = ABS(sigs*angs - nangls);
			angg = srg0*angbg[jrg][iz]+srg*angbg[jrg+1][iz];
                        angg = ABS(sigg*angg - nanglg);
			sigmas = srs0*sigbs[jrs][iz]+srs*sigbs[jrs+1][iz]; 
			sigmag = srg0*sigbg[jrg][iz]+srg*sigbg[jrg+1][iz]; 
                        ampd = cos(angs)*sigmag + cos(angg)*sigmas;
			ampd /= (cos(nangls)*cos(nanglg)*sqrt(sigmas*sigmag));

        /* Filter of 90 degrees to the operator (Peels,1988)

           Peels, G. L., 1988, True amplitude wave field extrapolation
           with applications in  seismic shot record redatuming, PhD
           thesis, Delft University of Technology.              */

                        if(ABS(angs)>=(PI/2) || ABS(angg)>=(PI/2)) {
                                ampd=0.0;
                        }

			if(ampd<0.0) ampd = -ampd;
			ampt[ix][iz] = ampd;

			pd = srs0*pbs[jrs][iz]+srs*pbs[jrs+1][iz]+sigp 
			     *(srg0*pbg[jrg][iz]+srg*pbg[jrg+1][iz]);
			if(pd<0.0) pd = -pd;
			temp = pd*dxm*odt;
			if(temp<1) temp = 1.0;
			if(temp>mtmax) temp = mtmax;
			ampti[ix][iz] = ampd/(temp*temp);
			tmt[ix][iz] = temp;
			if(pd<pmin && zpt[ix]>fzt+(nzt-1.1)*dzt) 
				zpt[ix] = fzt+iz*dzt;

		}
	}

	nxf = (xm-aperx-fx)/dx+0.5;
	if(nxf<0) nxf = 0;
	nxe = (xm+aperx-fx)/dx+0.5;
	if(nxe>=nx) nxe = nx-1;
	
	/* interpolate amplitudes and filter length along lateral	*/
	for(ix=nxf; ix<=nxe; ++ix){
		x = fx+ix*dx;
		dis = (xm>=x)?xm-x:x-xm;
		izt0 = (dis*rxz-fzt)/dzt;
		if(izt0<0) izt0 = 0;
		if(izt0>=nzt) izt0 = nzt-1;
		iz0 = (dis*rxz-fz)/dz;
		if(iz0<0) iz0 = 0;
		if(iz0>=nz) iz0 = nz-1;

		ax = (x-fxt)/dxt;
		jx = (int)ax;
		ax = ax-jx;
		if(ax<=0.01) ax = 0.;
		if(ax>=0.99) ax = 1.0;
		ax0 = 1.0-ax;
		if(jx>nxte-1) jx = nxte-1;
		if(jx<nxtf) jx = nxtf;
		if(jx>nxt-2) jx = nxt-2;
		if(jx<0) jx = 0;

		ar = (sx>=x)?(sx-x)/dx:(x-sx)/dx;
		jrs = (int)ar;
		if(jrs>nr-2) jrs = nr-2;
		srs = ar-jrs;
		srs0 = 1.0-srs;
		ar = (gx>=x)?(gx-x)/dx:(x-gx)/dx;
		jrg = (int)ar;
		if(jrg>nr-2) jrg = nr-2;
		srg = ar-jrg;
		srg0 = 1.0-srg;

		for(iz=izt0; iz<nzt; ++iz){
		    tzt[iz] = ax0*tsum[jx][iz]+ax*tsum[jx+1][iz]
				+srs0*tbs[jrs][iz]+srs*tbs[jrs+1][iz]
				+srg0*tbg[jrg][iz]+srg*tbg[jrg+1][iz];

		    amp[iz] = ax0*ampt[jx][iz]+ax*ampt[jx+1][iz];
		    ampi[iz] = ax0*ampti[jx][iz]+ax*ampti[jx+1][iz];
		    tm[iz] = ax0*tmt[jx][iz]+ax*tmt[jx+1][iz];

		}

		nzp = (ax0*zpt[jx]+ax*zpt[jx+1]-fz)/dz+1.5;
		if(nzp<iz0) nzp = iz0;
		if(nzp>nz) nzp = nz;

		/* interpolate along depth if operater aliasing 	*/
		for(iz=iz0; iz<nzp; ++iz) {
			az = z0+iz*rdz;
			jz = (int)az;
			if(jz>=nzt-1) jz = nzt-2;
			if(jz<0) jz = 0;
			sz = az-jz;
			sz0 = 1.0-sz;
			td = sz0*tzt[jz]+sz*tzt[jz+1];
			at = (td-ft)*odt+mtmax;
			jt = (int)at;
			if(jt > mtmax && jt < nt+mtmax-1){
			    ampd = sz0*ampi[jz]+sz*ampi[jz+1];
			    mt = (int)(0.5+sz0*tm[jz]+sz*tm[jz+1]);
			    res = at-jt;
			    res0 = 1.0-res;
 			    temp = (res0*(-trf[jt-mt]+2.0*trf[jt]-trf[jt+mt]) 
				+res*(-trf[jt-mt+1]+2.0*trf[jt+1]
				-trf[jt+mt+1]))*ampd;				
			    mig[ix][iz] += temp;

			}
		}

		/* interpolate along depth if not operater aliasing 	*/
		for(iz=nzp; iz<nz; ++iz) {
			az = z0+iz*rdz;
			jz = (int)az;
			if(jz>=nzt-1) jz = nzt-2;
			if(jz<0) jz = 0;
			sz = az-jz;
			sz0 = 1.0-sz;
			td = sz0*tzt[jz]+sz*tzt[jz+1];
			at = (td-ft)*odt;
			jt = (int)at;
			if(jt > 0 && jt < nt-1){
			    ampd = sz0*amp[jz]+sz*amp[jz+1];
			    res = at-jt;
			    res0 = 1.0-res;
 			    temp = (res0*trace[jt]+res*trace[jt+1])*ampd; 
			    mig[ix][iz] += temp;
			}
		}

	}

done:
	free2float(ampt);
	free2float(ampti);
	free2float(tmt);
	free1float(amp);
	free1float(ampi);
	free1float(zpt);
	free1float(tm);
	free1float(tzt);
	free1float(trf);
	return status;
}



/* Library version of SUMIGTOPO2D
 *
 * The main program (the parameters, the traces and their headers, the surface, the traveltime tables) is left to the caller.
 * The surface and the reference quantities are made by su_datumk2d_geometry() (with the recording surface for both of its
 * surfaces) and su_datumk2d_tables(), which are the functions of the same code in SUDATUMK2DR.
 *
 *	su_migtopo2d_trace:	migrates one trace into mig[nx][nz], the section of one offset (the contribution is added)
 *
 * trace[nt], ft, dt		the trace
 * sx, gx			source and receiver x
 * aperx			lateral aperture
 * nx, fx, dx, nz, fz, dz	the output section
 * ls				1 for a line source, 0 for a point source
 * mtmax, dxm, fmax, angmax	filter length of the anti-aliasing, midpoint interval, high cut and largest angle (degrees)
 * ns, fs, ds			the sources of the tables
 * nr, tb, pb, angb, sigb[ns][nr][nzt], ttab[ns][nxt][nzt]	as made by su_datumk2d_tables
 * nzt, fzt, dzt, nxt, fxt, dxt	the grid of the tables
 * nxi, fxi, dxi, nangl[nxi]	the angles of the normal of the surface with the vertical, at the input locations
 *
 * Returns 0, or 6 if the trace is too long for the filter. Indices that the program read outside of the tables are kept
 * inside them.
 */
int su_migtopo2d_trace(const float *trace, int nt, float ft, float dt, float sx, float gx, float *mig, float aperx,
	int nx, float fx, float dx, int nz, float fz, float dz, int ls, int mtmax, float dxm, float fmax, float angmax,
	int ns, float fs, float ds, int nr, const float *tb, const float *pb, const float *angb, const float *sigb,
	const float *ttab, int nzt, float fzt, float dzt, int nxt, float fxt, float dxt, int nxi, float fxi, float dxi,
	const float *nangl)
{
	int is,status;
	float as,res,nangls,nanglg;
	size_t i, n = (size_t) nxt*nzt, m = (size_t) nr*nzt;
	std::vector<float> tsum(n), tt(n), tbs(m), tbg(m), pbs(m), pbg(m), sigbs(m), sigbg(m), angbs(m), angbg(m),
		tr(trace, trace+nt);
	std::vector<float*> tsumr, tbsr, tbgr, pbsr, pbgr, sigsr, siggr, angsr, anggr, migr;

	/* the tables at the source */
	as = (sx-fs)/ds;
	is = (int)as;
	if (is>ns-2) is = ns-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	for (i=0; i<n; i++) tsum[i] = (1-res)*ttab[(size_t)is*n+i] + res*ttab[(size_t)(is+1)*n+i];
	for (i=0; i<m; i++) {
		size_t k = (size_t) is*m + i;
		pbs[i] = (1-res)*pb[k] + res*pb[k+m];
		tbs[i] = (1-res)*tb[k] + res*tb[k+m];
		sigbs[i] = (1-res)*sigb[k] + res*sigb[k+m];
		angbs[i] = (1-res)*angb[k] + res*angb[k+m];
	}

	/* and at the receiver */
	as = (gx-fs)/ds;
	is = (int)as;
	if (is>ns-2) is = ns-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	for (i=0; i<n; i++) {
		tt[i] = (1-res)*ttab[(size_t)is*n+i] + res*ttab[(size_t)(is+1)*n+i];
		tsum[i] = tt[i] + tsum[i];
	}
	for (i=0; i<m; i++) {
		size_t k = (size_t) is*m + i;
		pbg[i] = (1-res)*pb[k] + res*pb[k+m];
		tbg[i] = (1-res)*tb[k] + res*tb[k+m];
		sigbg[i] = (1-res)*sigb[k] + res*sigb[k+m];
		angbg[i] = (1-res)*angb[k] + res*angb[k+m];
	}

	as = (sx-fxi)/dxi;
	is = (int)as;
	if (is>nxi-2) is = nxi-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	nangls = (1-res)*nangl[is] + res*nangl[is+1];

	as = (gx-fxi)/dxi;
	is = (int)as;
	if (is>nxi-2) is = nxi-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	nanglg = (1-res)*nangl[is] + res*nangl[is+1];

	rows_of(tsum.data(), nxt, nzt, tsumr);
	rows_of(tbs.data(), nr, nzt, tbsr);
	rows_of(tbg.data(), nr, nzt, tbgr);
	rows_of(pbs.data(), nr, nzt, pbsr);
	rows_of(pbg.data(), nr, nzt, pbgr);
	rows_of(sigbs.data(), nr, nzt, sigsr);
	rows_of(sigbg.data(), nr, nzt, siggr);
	rows_of(angbs.data(), nr, nzt, angsr);
	rows_of(angbg.data(), nr, nzt, anggr);
	rows_of(mig, nx, nz, migr);

	status = mig2d(tr.data(),nt,ft,dt,sx,gx,migr.data(),aperx,nx,fx,dx,nz,fz,dz,ls,mtmax,dxm,fmax,angmax,
		tbsr.data(),tbgr.data(),pbsr.data(),pbgr.data(),angsr.data(),anggr.data(),nr,tsumr.data(),nzt,fzt,dzt,
		nxt,fxt,dxt,NULL,nangls,nanglg,sigsr.data(),siggr.data());
	return status;
}
