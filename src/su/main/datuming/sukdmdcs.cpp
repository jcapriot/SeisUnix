/* Omega domain filtering of a trace by sqrt(-i omega) (the filtering of the program, with the frequency of the
   negative frequencies by the transform's length also where it is odd).
   trace[nt]	the trace, replaced by the filtered one
   Returns 1 if the padded length is too long. */
static int filt(float *trace,int nt,float dt,int sgn)
{
	int  it,iw,sgnw,nfft,n;
	float temp, const2, amp, omega, dw;

	/* the multiplication by sqrt(-i) is a phase shift of pi/4, applied in Euler form: const2=cos(pi/4)=sin(pi/4) */
	const2 = 0.5*sqrt(2.0);

	nfft = npfao(2*nt,4*nt);
	if (nfft >= SU_NFLTS || nfft >= 720720) return 1;
	n = nfft/2;
	dw = 2.0*PI/(nfft*dt);

	std::vector<std::complex<float> > ct(nfft, std::complex<float>(0.0f, 0.0f));
	for(it=0; it<nt; ++it) ct[it] = trace[it];

	pfacc(1,nfft,ct.data());

	/* omega-domain filtering for point source - 2.5D */
	for(iw=0; iw<nfft; ++iw){
		float r, i;
		if (iw<=n) { omega = iw*dw; sgnw = 1; }
		else { omega = (iw-nfft)*dw; sgnw = -1; }
		amp = sqrt(ABS(omega));
		r = ct[iw].real(); i = ct[iw].imag();
		temp = (r-sgnw*i)*amp*const2;
		ct[iw] = std::complex<float>(temp, (sgnw*r + i)*amp*const2);
	}

	pfacc(-1, nfft, ct.data());

	for (it=0; it<nt; ++it) trace[it] = ct[it].real()/nfft;
	return 0;
}

/* the rows of a flat array */
static void rows_of(const float *base, int nrow, int len, std::vector<float*> &rows)
{
	int i;
	rows.resize(nrow);
	for (i=0; i<nrow; i++) rows[i] = (float *) (base + (size_t) i*len);
}
static int dat2d(float *trace,int nt,float ft,float dt,float sx,float gx,
             float **dat,float aperx,int nxso,float fxin,float dxso,
             float nzo,float fzo,float dzo,
             int nxi,float fxi,float dxi,
	     float **tsum,int sgn,
             int nzt,float fzt,float dzt,int nxt,float fxt,float dxt,
             float **szif,float v0,int dc,int ngl,float freq)

/*****************************************************************************
Datum source on one trace 
******************************************************************************
Input:
*trace		one seismic trace 
nt		number of time samples in seismic trace
ft		first time sample of seismic trace
dt		time sampleing interval in seismic trace
sx,gx		lateral coordinates of source and geophone (ignored)
aperx		lateral aperature in datuming
nxso,fxin,dxso  traces in output 
nzo,fzo,dzo     interpolation variables to define surfaces	
fxi             x-coordinate of the first surface location
dxi             horizontal spacing on surface
nxi             number of surface locations
tsum            sum of residual traveltimes from shot and receiver
nxt,fxt,dxt,nzt,fzt,dzt        dimension parameters of traveltime table
szif            array[] of the z component of the reference surfaces
dc              flag for previously downward continued receivers (dc=1)
ngl             number of geophone locations = number of receiver gathers

Output:
dat		Redatumed section
*****************************************************************************/
{
	int nxf,nxe,it,ix,iz,jz,jt,jx,mr;
	float x,z,ampd,res0,am,am0,ax,ax0;
	float odt=1.0/dt,az,sz,sz0,at,tio,res,temp,h;
        float p,q,s,ctau,xst=0.0,zst=0.0,ris,ros,rg,t0=0.0,sing;
        float xp,zgx,hp,phi=0.0,sxp,zs,zi,zip,atol;
	float *tzt;
	int status = 0;
        float zp=0.0,dzde=0.0,g,xs;


        /* set a tolerance variable to deal with numerical problems */
        atol = 1e-10; 

	/* allocate memory for datuming */
	tzt = alloc1float(nzt);
	memset((void *) tzt,0,nzt*sizeof(float));

        h = (gx>=sx)?(gx-sx)/2.0:(sx-gx)/2.0;
	/* fxf = fxi + (nxi-2)*dxi; */

        /* call to filt will perform the frequency domain filtering  */
        /* on the input data trace, returning in variable trace.     */  

        if (filt(trace,nt,dt,sgn)) { status = 6; goto done; }                


        /* calculate the limits of the aperture in the output */
	nxf = (sx-aperx-fxin)/dxso;
	if(nxf<0) nxf = 0;
        nxe = (sx+aperx-fxin)/dxso;
	if(nxe>=nxso) nxe = nxso-1;


        /* error if survey length exceeds topography definition */ 
        am = (fxin-fxi)/dxi;
        mr = (int)am;
        am = am - mr;
        if(am<=0.01) am = 0.;
        if(am>=0.99) am = 1.0;
        am0 = 1.0-am;
        if(mr<0) mr = 0;
        if(mr+nxe>nxi-1)
                { status = 1; goto done; }
	

        /* depth of the input source(zi) on the recording surface */

        am = (sx-fxi)/dxi;
        mr = (int)am;
        am = am - mr;
        if(am<=0.01) am = 0.;
        if(am>=0.99) am = 1.0;
        am0 = 1.0-am;
        if(mr<0) mr = 0;

        if(mr>=nxi-1){
           mr=nxi-2;
           am0 = 0.0;
           am = 1.0;
        }

        zi = ABS(am0*szif[mr][0]+am*szif[mr+1][0]);
        if(zi>=(nzo*dzo)+fzo)
              { status = 2; goto done; }


        /* approximate the surface derivative near this input location */

        if(mr==0){ 
           zp = szif[mr+1][0]-szif[mr][0];
           dzde = zp/dxi;         
        }else{
           zp = (szif[mr][0]-szif[mr-1][0]) + (szif[mr+1][0]-szif[mr][0]);
           dzde = zp/(2*dxi);
        }


        /* depth of the geophone location(zgx), depending on whether */
        /* it has previously been downward continued.  if not, put it   */
        /* on the recording surface, if so, put it on the datuming surface. */

        am = (gx-fxi)/dxi;
        mr = (int)am;
        am = am - mr;
        if(am<=0.01) am = 0.;
        if(am>=0.99) am = 1.0;
        am0 = 1.0-am;
        if(mr<0) mr = 0;

        if(mr>=nxi-1){
           mr=nxi-2;
           am0 = 0.0;
           am = 1.0;
        }

        if(!dc){

            zgx = ABS(am0*szif[mr][0]+am*szif[mr+1][0]);
            if(zgx>=(nzo*dzo)+fzo)
                  { status = 2; goto done; }

        }else{

            zgx = ABS(am0*szif[mr][1]+am*szif[mr+1][1]);
            if(zgx>=(nzo*dzo)+fzo)
                  { status = 2; goto done; }
        }


        /* loop over the lateral aperture in the output section */
	for(ix=nxf; ix<=nxe; ++ix){
		x = fxin+ix*dxso;

		ax = (x-fxt)/dxt;
		jx = (int)ax;
		ax = ax-jx;
		if(ax<=0.01) ax = 0.;
		if(ax>=0.99) ax = 1.0;
		ax0 = 1.0-ax;
		if(jx>nxt-2) jx = nxt-2;
		if(jx<0) jx = 0;


                /* determine the time tio from the source location of this */
                /* input trace to the source location of this output trace */
                /* by building a vector of times to all depths, then interp- */
                /* -olating to the exact datuming depth.                     */

		for(iz=0; iz<nzt; ++iz){
		    tzt[iz] = ax0*tsum[jx][iz]+ax*tsum[jx+1][iz];
		}


                /* datum depth at this output source location(z) */
  
                am = (x-fxi)/dxi;
                mr = (int)am;
                am = am - mr;
                if(am<=0.01) am = 0.;
                if(am>=0.99) am = 1.0;
                am0 = 1.0-am;
                if(mr<0) mr = 0;

                if(mr>=nxi-1){
                     mr=nxi-2;
                     am0 = 0.0;
                     am = 1.0;
                }
 
                z = ABS(am0*szif[mr][1]+am*szif[mr+1][1]);
                if(z<=fzo || z>=fzo+(nzo*dzo))                                                    
                      { status = 3; goto done; }    



                /* calculate travel time between datum and surface */
                az = (z-fzo)/dzt;
                jz = (int)az;
                if(jz>=nzt-1) jz = nzt-2;
                if(jz<0) jz = 0;
                sz = az-jz;
                sz0 = 1.0-sz;
                tio = sz0*tzt[jz]+sz*tzt[jz+1];


/* add this for exact straight ray calc */

/*
                tio =  sqrt((x-sx)*(x-sx)+(z-zi)*(z-zi))/v0;
*/

/*                                      */


                at = (sgn*tio-ft)*odt;

                /* loop over times along the output trace, and add to the */
                /* sum at the output point [ix,it] any amplitude on the   */
                /* data trace at time it+-tio.                            */

		jt = (int)at;
                res = ABS(at-jt);
                res0 = 1.0-res;


                /* only sources on the lesser side of this receiver location are in */
                /* this gather by the required geometry.  if the output location is */
                /* not, do not use it.                                              */
 
                if(x<=gx){

                  /* define the time along the singular path */  
                  sing = sqrt((gx-x)*(gx-x)+(z-zgx)*(z-zgx))/v0;

                  /* define the rotation */
                  if(x==gx){
                    if(dc==0) phi = PI/2.0;
                    if(dc==1) phi = 0.0;
                  }else{
                    phi = atan((z-zgx)/(x-gx));      
                  }

                  /* coordinate shift-rotation */
                  xp = (x-gx)*cos(phi)+(z-zgx)*sin(phi);
                  hp = 0.5*xp;
                  sxp = (sx-gx)*cos(phi)+(zi-zgx)*sin(phi);
                  zip = -(sx-gx)*sin(phi)+(zi-zgx)*cos(phi);

                  if(dc==0 && hp==0.0) { status = 4; goto done; }


                  /* loop over output times */
                  for (it=0; it<nt; it++){
		    if(it+jt >= (sgn<0?1:0) && jt < nt-it-sgn){
  
                     t0 = ft+(it*dt); 

                     if(t0<sing+atol){ 

                        ampd=0.0;

                     }else{                
  
                        /* calculate the coordinates of the stationary point */
                        /* in the shifted-rotated frame */


                        if(dc==0){

                           if(h==0.0){

                              xst=hp+v0*t0/2.0; 
                              zst=0.0;

                           }else{

                              ctau = (v0*t0)*(v0*t0); 
                              q = (ctau-4.0*hp*hp)/(4.0*ctau); 

                              p = 2.0*q*(sxp-xp)*(xp)*zip;      
                              p = p/((zip*zip) + 4.0*q*(sxp-xp)*(sxp-xp));    

                              s = q*zip*zip*(ctau - (xp*xp));          
                              s = s/((zip*zip) + 4.0*q*(sxp-xp)*(sxp-xp));                           

                              zst = sqrt(s+(p*p))-p;        
                              xst = ((sxp-xp)/zip)*zst + xp;

                              if(zst<0.0) { status = 5; goto done; } 

                           }
                        }

                        if(dc==1 && hp!=0.0){

                           if(h==0.0){

                              xst=hp+v0*t0/2.0; 
                              zst=0.0;

                           }else{

                              ctau = (v0*t0)*(v0*t0); 
                              q = (ctau-4.0*hp*hp)/(4.0*ctau); 

                              p = 2.0*q*(sxp-xp)*(xp)*zip;      
                              p = p/((zip*zip) + 4.0*q*(sxp-xp)*(sxp-xp));    

                              s = q*zip*zip*(ctau - (xp*xp));          
                              s = s/((zip*zip) + 4.0*q*(sxp-xp)*(sxp-xp));                  

                              zst = sqrt(s+(p*p))-p;        
                              xst = ((sxp-xp)/zip)*zst + xp;

                              if(zst<0.0) { status = 5; goto done; } 

                           }
                        }
                            
                        if(dc==1 && hp==0.0){

                              xst = -(0.5)*(t0*v0*sxp)/sqrt((sxp*sxp)+(zip*zip));  
                              zst = ABS((0.5)*(t0*v0*zip)/sqrt((sxp*sxp)+(zip*zip)));        

                        }


                        /* rotate back to unprimed coords */

                        xs = xst*cos(phi)-zst*sin(phi)+sx;
                        zs = xst*sin(phi)+zst*cos(phi)+zgx;           
                  /*    if(zs<0) err("Negative zs...\n");    */

                        /* calculate path lenghts */

                        ris = sqrt((xst-sxp)*(xst-sxp) + (zst-zip)*(zst-zip));
                        ros = sqrt((xst-xp)*(xst-xp) + (zst)*(zst));     
                        rg = sqrt((xst)*(xst) + (zst*zst));    

                   /*   if(ris<=0. || ros<=0. || rg<0.) warn("Negative path length!\n");  */
                   /*   if(ris<=ros) warn("St. pnt. not below output!\n");   */

                        /* calculate G(xs,zs) */ 

                        g = (zs-zi)-dzde*(xs-sx);

                        /* calculate the amplitude weight */

                        ampd = g*sqrt(rg+ris)/ris;                 
                        ampd = ampd/(sqrt(rg+ros)*sqrt(ABS(ris-ros)));                       

                        /* check to see if this is a valid stationary point */
                        if((ris-ros)<(v0/(4*freq))) ampd = 0.0;                           
                        if(zs<0.) ampd = 0.0;
                        if(ris<=ros) ampd=0.0;
                        if(ris<0. || ros<0. || rg<0.) ampd=0.0;

                     }             

  
                     /* find the correct time data, scale by amplitude, and */
                     /* assign to output array. */ 

                     temp=(res0*trace[it+jt]+res*trace[it+jt+sgn])*ampd;
                     dat[ix][it] += temp;       


                    }
              	}

              }
	}

done:
	free1float(tzt);
	return status;
}


/* The datuming of the sources of one trace of a receiver gather into the output gather, the loop body of the program
 * (the datuming is downward: sgn = 1).
 *
 * dat[nxso][nt], nxso, fxin, dxso	the output traces (the sources) and their positions
 * dc			0 for receivers on the recording surface, 1 for those that are on the datum
 * ngl			the number of receiver gathers
 * the rest as su_kdmdcr_trace
 *
 * Returns 0; 1 if the surfaces do not cover the output, 2 if the recording surface or the datum is out of the depths,
 * 3 if the datum is out of the traveltime range, 4 if the datum and recording surfaces overlap, 5 if a stationary point
 * is above the datum, 6 if the trace is too long. Differences from the program, which are its bugs: indices that read
 * outside of the tables are kept inside.
 */
int su_kdmdcs_trace(const float *trace, int nt, float ft, float dt, float sx, float gx, float *dat, float aperx,
	int nx, float fxin, float dxso, int nzo, float fzo, float dzo, int nxi, float fxi, float dxi, int ns, float fs,
	float ds, const float *ttab, int nzt, float fzt, float dzt, int nxt, float fxt, float dxt, const float *szif,
	float v0, int dc, int ngl, float freq)
{
	int is;
	float as, res;
	std::vector<float> tsum((size_t) nxt*nzt), tr(trace, trace+nt);
	std::vector<float*> tsumr, datr, szr;

	/* interpolate the travel time table to the location of the trace */
	as = (sx-fs)/ds;
	is = (int)as;
	if (is>ns-2) is = ns-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	{
		size_t i, n = (size_t) nxt*nzt;
		const float *t1 = ttab + (size_t) is*n;
		for (i=0; i<n; i++) tsum[i] = (1-res)*t1[i] + res*t1[i+n];
	}
	rows_of(tsum.data(), nxt, nzt, tsumr);
	rows_of(dat, nx, nt, datr);
	rows_of(szif, nxi, 2, szr);

	return dat2d(tr.data(),nt,ft,dt,sx,gx,datr.data(),aperx,nx,fxin,dxso,nzo,fzo,dzo,nxi,fxi,dxi,tsumr.data(),1,nzt,fzt,
		dzt,nxt,fxt,dxt,szr.data(),v0,dc,ngl,freq);
}
