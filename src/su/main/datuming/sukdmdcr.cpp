/* Omega domain filtering of a trace by sqrt(-i omega) (the filtering of the program, with the frequency of the
   negative frequencies by the transform's length also where it is odd).
   trace[nt]	the trace, replaced by the filtered one
   Returns 1 if the padded length is too long. */
static int filt(float *trace,int nt,float dt,int sgn)
{
	int  it,iw,sgnw,nfft,n;
	float temp, const2, amp, omega, dw;

	/* the multiplication by sqrt(-i) is a phase shift of pi/4, applied in Euler form: const2=cos(pi/4)=sin(pi/4) */
	const2 = 0.5*sqrt(2.0);

	nfft = npfao(2*nt,4*nt);
	if (nfft >= SU_NFLTS || nfft >= 720720) return 1;
	n = nfft/2;
	dw = 2.0*PI/(nfft*dt);

	std::vector<std::complex<float> > ct(nfft, std::complex<float>(0.0f, 0.0f));
	for(it=0; it<nt; ++it) ct[it] = trace[it];

	pfacc(1,nfft,ct.data());

	/* omega-domain filtering for point source - 2.5D */
	for(iw=0; iw<nfft; ++iw){
		float r, i;
		if (iw<=n) { omega = iw*dw; sgnw = 1; }
		else { omega = (iw-nfft)*dw; sgnw = -1; }
		amp = sqrt(ABS(omega));
		r = ct[iw].real(); i = ct[iw].imag();
		temp = (r-sgnw*i)*amp*const2;
		ct[iw] = std::complex<float>(temp, (sgnw*r + i)*amp*const2);
	}

	pfacc(-1, nfft, ct.data());

	for (it=0; it<nt; ++it) trace[it] = ct[it].real()/nfft;
	return 0;
}

/* the rows of a flat array */
static void rows_of(const float *base, int nrow, int len, std::vector<float*> &rows)
{
	int i;
	rows.resize(nrow);
	for (i=0; i<nrow; i++) rows[i] = (float *) (base + (size_t) i*len);
}
static int dat2d(float *trace,int nt,float ft,float dt,float sx,float gx,
	     float **dat,float aperx,int nxgo,float fxin,float dxgo,
  	     float nzo,float fzo,float dzo,
	     int nxi,float fxi,float dxi,
	     float **tsum,int sgn,
             int nzt,float fzt,float dzt,int nxt,float fxt,float dxt,
             float **szif,float v0,float freq)
             
/*****************************************************************************
Datum receiver on one trace 
******************************************************************************
Input:
*trace		one seismic trace 
nt		number of time samples in seismic trace
ft		first time sample of seismic trace
dt		time sampling interval in seismic trace
sx,gx		lateral coordinates of source and geophone (ignored)
aperx		lateral aperture in the datuming process
nxgo,fxin,dxgo  traces in output
nzo,fzo,dzo     interpolation variables to define surfaces	
fxi             x-coordinate of the first surface location
dxi             horizontal spacing on surface
nxi             number of input surface locations
tsum		sum of residual traveltimes from shot and receiver
nxt,fxt,dxt,nzt,fzt,dzt		dimension parameters of traveltime table
szif            array[] of the z component of the reference surfaces

Output:
dat		Redatumed section
*****************************************************************************/
{
        int nxf,nxe,it,ix,iz,jz,jt,jx,mr;
        float x,z,ampd,res0,am,am0;
	float ax,ax0,odt=1.0/dt,az,sz,sz0,at,tio,res,temp,h;
	float p,q,s,ctau,xst=0.0,zst=0.0,rig,sing,t0,rog,rs,zi,zsx,zs;
        float phi,xp,hp,gxp,zip,atol;
	float *tzt;
	int status = 0;
        float zp=0.0,dzde=0.0,g,xs;


        /* set a tolerance variable to deal with numerical problems */
        atol = 1e-10; 

	/* allocate memory for datuming */
	tzt = alloc1float(nzt);
	memset((void *) tzt,0,nzt*sizeof(float));

        h = (gx>=sx)?(gx-sx)/2.0:(sx-gx)/2.0;
        /* fxf = fxi + (nxi-2)*dxi; */

        /* call to filt will perform the frequency domain filtering */
        /* on the input data trace, returning in variable trace.    */  
	
  	if (filt(trace,nt,dt,sgn)) { status = 6; goto done; }            


        /* calculate the limits of the output  */
        nxf = (gx-aperx-fxin)/dxgo;
        if(nxf<0) nxf = 0;
        nxe = (gx+aperx-fxin)/dxgo;
        if(nxe>=nxgo) nxe = nxgo-1;


        /* error if survey length exceeds topography definition */
	am = (fxin-fxi)/dxi;
	mr = (int)am;
	am = am - mr;
	if(am<=0.01) am = 0.;
	if(am>=0.99) am = 1.0;
	am0 = 1.0-am;
	if(mr<0) mr = 0;
	if(mr+nxe>nxi-1)
                { status = 1; goto done; }


        /* depth of the input receiver (zi) on the recording surface */
        am = (gx-fxi)/dxi;
        mr = (int)am;
        am = am - mr;
        if(am<=0.01) am = 0.;
        if(am>=0.99) am = 1.0;
        am0 = 1.0-am;
        if(mr<0) mr = 0;

        if(mr>=nxi-1){
           mr=nxi-2;
           am0 = 0.0;
           am = 1.0;
        }

        zi = ABS(am0*szif[mr][0]+am*szif[mr+1][0]);
        if(zi>=fzo+(nzo*dzo))
                 { status = 2; goto done; }


        /* approximate the surface derivative near this input location */
        if(mr==0){ 
           zp = szif[mr+1][0]-szif[mr][0];
           dzde = zp/dxi;         
        }else{
           zp = (szif[mr][0]-szif[mr-1][0]) + (szif[mr+1][0]-szif[mr][0]);
           dzde = zp/(2*dxi);
        }


        /* depth of the source location(zsx) */
        am = (sx-fxi)/dxi;
        mr = (int)am;
        am = am - mr;
        if(am<=0.01) am = 0.;
        if(am>=0.99) am = 1.0;
        am0 = 1.0-am;
        if(mr<0) mr = 0;

        if(mr>=nxi-1){
           mr=nxi-2;
           am0 = 0.0;
           am = 1.0;
        }

        zsx = ABS(am0*szif[mr][0]+am*szif[mr+1][0]);
        if(zsx>=fzo+(nzo*dzo))
                { status = 2; goto done; }


	
	/* loop over the lateral aperture in the output section	*/
	for(ix=nxf; ix<=nxe; ++ix){
		x = fxin+ix*dxgo;

		ax = (x-fxt)/dxt;
		jx = (int)ax;
		ax = ax-jx;
		if(ax<=0.01) ax = 0.;
		if(ax>=0.99) ax = 1.0;
		ax0 = 1.0-ax;
		if(jx>nxt-2) jx = nxt-2;
		if(jx<0) jx = 0;

                /* determine the time tio from the receiver location of this */
                /* input trace to the receiver location of this output trace */
                /* by building a vector of times to all depths, then interp- */
                /* -olating to the exact datuming depth.                     */

  		for(iz=0; iz<nzt; ++iz){                           
		    tzt[iz] = ax0*tsum[jx][iz]+ax*tsum[jx+1][iz];
             	}

		/* datuming depth at this output location (z) */

                am = (x-fxi)/dxi;
                mr = (int)am;
                am = am - mr;
                if(am<=0.01) am = 0.;
                if(am>=0.99) am = 1.0;
                am0 = 1.0-am;
                if(mr<0) mr = 0;

                if(mr>=nxi-1){
                    mr=nxi-2;
                    am=0.0; 
                    am0=1.0;
                }

                z = ABS(am0*szif[mr][1]+am*szif[mr+1][1]);
                if(z<=fzo || z>=fzo+(nzo*dzo))                                                    
                        { status = 3; goto done; }    


                /* determine the travel time between datum and surface */ 
                az = (z-fzo)/dzt;
                jz = (int)az;
                if(jz>=nzt-1) jz = nzt-2;
                if(jz<0) jz = 0;
                sz = az-jz;
                sz0 = 1.0-sz;
                tio = sz0*tzt[jz]+sz*tzt[jz+1];

/*  this is added for straight ray calc  */

/*
                tio = sqrt((x-gx)*(x-gx)+(z-zi)*(z-zi))/v0;       
*/

/*                                       */


                at = (sgn*tio-ft)*odt;

                /* loop over times along the output trace, and add to the */
                /* sum at the output point [ix,it] any amplitude on the   */
                /* data trace at time it+tio.                            */

                jt = (int)at;
                res = ABS(at-jt);
                res0 = 1.0-res;


                /* only receivers on the greater side of this source location are in */
                /* this gather by the required geometry.  if the output location is */
                /* not, do not use it.                                              */


                if(x>=sx){


                   /* define the time along the singular path */
                   sing = sqrt((sx-x)*(sx-x)+(zsx-z)*(zsx-z))/v0;


                   /* define the coordinates in the shifted-rotated frame */
                   if(x==sx){
                     phi = PI/2.0;
                   }else{
                     phi = atan((z-zsx)/(x-sx));      
                   }

                   xp = (x-sx)*cos(phi)+(z-zsx)*sin(phi);
                   hp = 0.5*xp;
                   gxp = (gx-sx)*cos(phi)+(zi-zsx)*sin(phi);
                   zip = -(gx-sx)*sin(phi)+(zi-zsx)*cos(phi);

                   if(hp==0.0) { status = 4; goto done; }


                   /* loop over output times */
                   for (it=0; it<nt; it++){
                     if(it+jt >= (sgn<0?1:0) && jt < nt-it-sgn){
  
                      t0 = ft+(it*dt);
  
                      if(t0<sing+atol){
  
                         ampd=0.0;

                      }else{ 

                          /* calculate the coordinates of the stationary point */
                          /* in the shifted-rotated frame */

                          if(h==0.0){

                             xst=hp+v0*t0/2.0; 
                             zst=0.0;

                          }else{

                             ctau = (v0*t0)*(v0*t0); 
                             q = (ctau-4.0*hp*hp)/(4.0*ctau); 
 
                             p = 2.0*q*(gxp-xp)*xp*zip;      
                             p = p/((zip*zip) + 4.0*q*(gxp-xp)*(gxp-xp));    
 
                             s = q*zip*zip*(ctau - (xp*xp));          
                             s = s/((zip*zip) + 4.0*q*(gxp-xp)*(gxp-xp));                         

                             zst = sqrt(s+(p*p))-p;        
                             xst = ((gxp-xp)/zip)*zst + xp;

                      /*     if(zst<0.0) err("Negative zst!\n");  */

                          }


                          /* rotate back to unprimed coords */

                          xs = xst*cos(phi)-zst*sin(phi)+sx;
                          zs = xst*sin(phi)+zst*cos(phi)+zsx;           
                      /*  if(zs<0) err("Negative zs...\n");    */

                          /* calculate path lengths */

                          rig = sqrt((xst-gxp)*(xst-gxp) + (zst-zip)*(zst-zip));
                          rog = sqrt((xst-xp)*(xst-xp) + (zst)*(zst));     
                          rs = sqrt((xst)*(xst) + (zst*zst));    

                      /*  if(rig<0. || rog<0. || rs<0.) warn("Negative path length!\n");
                          if(rig<=rog) warn("St. pnt. not below output!\n");  */

                          /* calculate G(xs,zs) */ 

                          g = (zs-zi)-dzde*(xs-gx);

                          /* calculate the amplitude weight */

                          ampd = g*sqrt(rs+rig)/rig;                 
                          ampd = ampd/(sqrt(rs+rog)*sqrt(ABS(rig-rog)));      

                          /* check to see if this is a valid stationary point */
                          if((rig-rog)<(v0/(4*freq))) ampd = 0.0;                           
                          if(zs<0.) ampd = 0.0;
                          if(rig<=rog) ampd=0.0;
                          if(rig<0. || rog<0. || rs<0.) ampd=0.0;


                      }                

	    	      /* find the correct time data, scale by amplitude, and */
                      /* assign to output array. */ 

                      temp=(res0*trace[it+jt]+res*trace[it+jt+sgn])*ampd;
                      dat[ix][it] += temp;     


                    } 
                }

              }
	}

done:
	free1float(tzt);
	return status;
}


/* The datuming of the receivers of one trace of a shot gather into the output gather, the loop body of the program
 * (the datuming is downward: sgn = 1).
 *
 * trace[nt]		the input trace
 * ft, dt		first time and sample interval
 * sx, gx		the source and receiver x of the trace
 * dat[nxgo][nt]	the output traces, to which the contribution is added
 * aperx		lateral aperture
 * nxgo, fxin, dxgo	the output positions
 * nzo, fzo, dzo	the depth samples of the output, which define the range of depths of the surfaces
 * nxi, fxi, dxi	the number, first and interval of the locations of the surfaces
 * ns, fs, ds		sources of the traveltime tables
 * ttab[ns][nxt][nzt]	the traveltime tables
 * nzt, fzt, dzt, nxt, fxt, dxt		the grid of the tables
 * szif[nxi][2]		the depths of the recording surface (0) and of the datum (1) at the locations
 * v0, freq		the reference velocity, and the dominant frequency
 *
 * Returns 0; 1 if the surfaces do not cover the output, 2 if the recording surface is out of the depths, 3 if the datum is
 * out of the traveltime range (or on the top of it), 4 if the datum and recording surfaces overlap, 6 if the trace is too
 * long. Differences from the program, which are its bugs: indices that read outside of the tables are kept inside.
 */
int su_kdmdcr_trace(const float *trace, int nt, float ft, float dt, float sx, float gx, float *dat, float aperx,
	int nx, float fxin, float dxgo, int nzo, float fzo, float dzo, int nxi, float fxi, float dxi, int ns, float fs,
	float ds, const float *ttab, int nzt, float fzt, float dzt, int nxt, float fxt, float dxt, const float *szif,
	float v0, float freq)
{
	int is;
	float as, res;
	std::vector<float> tsum((size_t) nxt*nzt), tr(trace, trace+nt);
	std::vector<float*> tsumr, datr, szr;
	const int nxo = nx;
	(void) nxo;

	/* interpolate the travel time table to the location of the trace */
	as = (gx-fs)/ds;
	is = (int)as;
	if (is>ns-2) is = ns-2;
	if (is<0) is = 0;
	res = as-is;
	if (res<=0.01) res = 0.0;
	if (res>=0.99) res = 1.0;
	{
		size_t i, n = (size_t) nxt*nzt;
		const float *t1 = ttab + (size_t) is*n;
		for (i=0; i<n; i++) tsum[i] = (1-res)*t1[i] + res*t1[i+n];
	}
	rows_of(tsum.data(), nxt, nzt, tsumr);
	rows_of(dat, nx, nt, datr);
	rows_of(szif, nxi, 2, szr);

	return dat2d(tr.data(),nt,ft,dt,sx,gx,datr.data(),aperx,nx,fxin,dxgo,nzo,fzo,dzo,nxi,fxi,dxi,tsumr.data(),1,nzt,fzt,
		dzt,nxt,fxt,dxt,szr.data(),v0,freq);
}
